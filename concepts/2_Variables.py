# Variables
# It is a name that refers to a value (object) stored in program.
# It allows us to store data, access it later, and change what value the name refers to.

name = "Selvakumar"  # string variable
age = 24  # integer variable
name = "SK" # changing the value of the variable 'name'
is_student = True  # boolean variable

print("My name is", name, "and I am", age, "years old.")
print("I am a student:", is_student)

# Naming rules
# Allowed:
user_name = "Selva"
userName = "Selva"
age2 = 24
_private = "secret"

# Not allowed:
# 2name = "Selva"  # starts with a number
# my-name = "Selva"  # contains a hyphen
# my name = "Selva"  # contains a space
# class = "Math"  # 'class' is a reserved keyword in Python

